def _decode_body(payload: dict) -> str:
    """Extract and decode the text body from a Gmail message payload."""
    parts = []
    if "body" in payload and payload["body"].get("data"):
        data = payload["body"]["data"]
        # URL-safe base64
        padded = data + "=" * (4 - len(data) % 4)
        try:
            decoded = base64.urlsafe_b64decode(padded).decode("utf-8", errors="replace")
            parts.append(decoded)
        except Exception:
            pass

    if "parts" in payload:
        for part in payload["parts"]:
            mime = part.get("mimeType", "")
            if mime == "text/plain" and part.get("body", {}).get("data"):
                data = part["body"]["data"]
                padded = data + "=" * (4 - len(data) % 4)
                try:
                    decoded = base64.urlsafe_b64decode(padded).decode("utf-8", errors="replace")
                    parts.append(decoded)
                except Exception:
                    pass
            elif mime == "multipart/alternative":
                # Recurse into alternative parts
                inner = _decode_body(part)
                if inner:
                    parts.append(inner)

    return "\n".join(parts) if parts else ""


def _extract_headers(msg: dict) -> dict:
    """Extract key headers from a Gmail message."""
    headers = {}
    for h in msg.get("payload", {}).get("headers", []):
        name = h.get("name", "").lower()
        headers[name] = h.get("value", "")
    return headers


def _summarize_message(msg: dict, include_body: bool = False) -> dict:
    """Turn a Gmail API message dict into a clean summary."""
    headers = _extract_headers(msg)
    result = {
        "id": msg.get("id"),
        "thread_id": msg.get("threadId"),
        "from": headers.get("from", ""),
        "to": headers.get("to", ""),
        "subject": headers.get("subject", ""),
        "date": headers.get("date", ""),
        "snippet": msg.get("snippet", ""),
        "label_ids": msg.get("labelIds", []),
    }
    if include_body:
        result["body"] = _decode_body(msg.get("payload", {}))
    return result


