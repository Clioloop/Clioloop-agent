#!/usr/bin/env python3
"""
Gmail Tool Module — Full Gmail API access with auto-refreshing OAuth tokens.

Provides read, search, send, draft, label, and modify operations against the
Gmail API.  Token refresh is automatic: on every call the token is checked and
refreshed if expired before the API request is made.

Requirements:
    - ~/.clio/gmail/credentials.json  (Desktop OAuth client secrets from Google Cloud)
    - ~/.clio/gmail/token.json        (generated by the OAuth flow)
    - google-api-python-client, google-auth-httplib2, google-auth-oauthlib installed

Setup:
    Run ``python3 ~/.clio/gmail/gmail_auth.py`` once to authorise and generate
    token.json.  The tool handles the rest, including refresh.
"""

import json
import logging
import os
import threading
import time
import base64
from pathlib import Path
from typing import Optional

from tools.registry import registry

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Paths and constants
# ---------------------------------------------------------------------------

_GMAIL_DIR = Path(os.path.expanduser("~/.clio/gmail"))
_CRED_PATH = _GMAIL_DIR / "credentials.json"
_SCOPES = ["https://mail.google.com/"]

# Multi-account token paths: "1"-"3"
_TOKEN_PATHS = {
    "1": _GMAIL_DIR / "token.json",
    "2": _GMAIL_DIR / "token2.json",
    "3": _GMAIL_DIR / "token3.json",
}
# Default token path for backwards compatibility
_TOKEN_PATH = _TOKEN_PATHS["1"]

# Thread lock to prevent concurrent refresh races.
_token_lock = threading.Lock()

# ---------------------------------------------------------------------------
# Token management with auto-refresh
# ---------------------------------------------------------------------------

def _load_credentials(account: str = "1"):
    """Load credentials from the token file for the given account, refreshing if expired.

    Returns a valid Credentials object or raises RuntimeError.
    """
    from google.auth.transport.requests import Request
    from google.oauth2.credentials import Credentials

    account = account or "1"
    if account not in _TOKEN_PATHS:
        available = ", ".join(sorted(_TOKEN_PATHS))
        raise RuntimeError(
            f"Gmail account {account!r} is not configured. "
            f"Available account numbers: {available}."
        )

    token_path = _TOKEN_PATHS[account]
    if not token_path.exists():
        raise RuntimeError(
            f"Gmail token not found at {token_path}. "
            f"Run: python3 ~/.clio/gmail/gmail_auth.py (account {account})"
        )

    creds = Credentials.from_authorized_user_file(str(token_path), _SCOPES)

    # If expired but we have a refresh token, refresh it now.
    if not creds.valid and creds.expired and creds.refresh_token:
        with _token_lock:
            # Double-check after acquiring lock (another thread may have refreshed).
            creds = Credentials.from_authorized_user_file(str(token_path), _SCOPES)
            if not creds.valid and creds.expired and creds.refresh_token:
                logger.info(f"Gmail token expired (account {account}) — refreshing...")
                creds.refresh(Request())
                # Persist the refreshed token.
                token_path.write_text(creds.to_json(), encoding="utf-8")
                os.chmod(token_path, 0o600)
                logger.info(f"Gmail token refreshed and saved (account {account}).")

    if not creds.valid:
        raise RuntimeError(
            f"Gmail token is invalid and cannot be refreshed (account {account}). "
            "Re-authorise: python3 ~/.clio/gmail/gmail_auth.py"
        )

    return creds


def _get_service(account: str = "1"):
    """Build and return a Gmail API service object with valid credentials."""
    from googleapiclient.discovery import build
    creds = _load_credentials(account)
    return build("gmail", "v1", credentials=creds, cache_discovery=False)


def _check_gmail_requirements() -> bool:
    """Check whether Gmail tool prerequisites are met (at least one account)."""
    try:
        return _CRED_PATH.exists() and any(p.exists() for p in _TOKEN_PATHS.values())
    except Exception:
        return False


